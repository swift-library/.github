"""Render the organization profile from its reviewed catalog."""

import argparse
from html import escape
import json
from pathlib import Path
import subprocess


ROOT = Path(__file__).resolve().parent.parent


def read_catalog():
    catalog = json.loads((ROOT / "profile/catalog.json").read_text())
    names = [item["name"] for group in catalog["groups"] for item in group["repositories"]]
    navigation = list(catalog["navigation"].values())
    if len(names + navigation) != len(set(names + navigation)):
        raise ValueError("Every repository must have one catalog or navigation role")
    for group in catalog["groups"]:
        if not group["title"] or not group["repositories"]:
            raise ValueError("Catalog groups need a title and repositories")
        for item in group["repositories"]:
            if not 1 <= len(item["summary"]) <= 110 or not item["summary"].endswith("."):
                raise ValueError(f"Invalid outcome sentence for {item['name']}")
    return catalog, set(names + navigation)


def check_membership(organization, expected):
    pages = subprocess.check_output(
        ["gh", "api", "--paginate", "--slurp", f"orgs/{organization}/repos?type=public&per_page=100"],
        text=True,
    )
    actual = {repo["name"] for page in json.loads(pages) for repo in page
              if not repo["private"] and not repo["fork"]}
    if actual != expected:
        raise ValueError(f"Catalog membership differs: missing={sorted(actual - expected)}, "
                         f"not public/self-owned={sorted(expected - actual)}")


def render(catalog):
    organization = catalog["organization"]
    promise = catalog["promise"]
    standards = f"https://github.com/{organization}/{catalog['navigation']['standards']}/blob/master"
    lines = [
        "<!-- Generated by Scripts/render-profile.py from profile/catalog.json. -->",
        '<div align="center">', "",
        '<p align="center">',
        f'  <img src="https://raw.githubusercontent.com/{organization}/.github/master/Documentation/Assets/Logo.svg" width="128" alt="swift-library umbrella logo">',
        "</p>", "",
        f'<h1 align="center">{escape(promise["heading"])}</h1>', "",
        '<p align="center">', f'  {escape(promise["secondary"])}', "</p>", "",
        '<p align="center">',
        f'  <a href="https://{catalog["navigation"]["documentation"]}/">Documentation</a> ·',
        f'  <a href="{standards}/CONTRIBUTING.md">Contributing</a> ·',
        f'  <a href="{standards}/SECURITY.md">Security</a> ·',
        f'  <a href="{standards}/SUPPORT.md">Support</a>',
        "</p>", "", "</div>", "",
    ]
    for group in catalog["groups"]:
        lines += [f'### {group["title"]}', "", "<table>", "<tbody>"]
        for item in group["repositories"]:
            name = item["name"]
            url = f"https://github.com/{organization}/{name}"
            logo = f"https://raw.githubusercontent.com/{organization}/{name}/HEAD/Documentation/Assets/Logo.svg"
            summary = escape(item["summary"]).replace("|", "&#124;")
            lines.append(f'<tr><td><a href="{url}"><img src="{logo}" width="40" alt="{name} logo"></a></td>'
                         f'<td><strong><a href="{url}">{name}</a></strong><br>{summary}</td></tr>')
        lines += ["</tbody>", "</table>", ""]
    lines += ['<sub>Maintained by <a href="https://github.com/showxu">@showxu</a> (<a href="https://showxu.github.io">https://showxu.github.io</a>).</sub>', ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--check-membership", action="store_true")
    args = parser.parse_args()
    catalog, names = read_catalog()
    if args.check_membership:
        check_membership(catalog["organization"], names)
    output = ROOT / "profile/README.md"
    rendered = render(catalog)
    if args.check:
        if output.read_text() != rendered:
            raise SystemExit("Profile differs; run python3 Scripts/render-profile.py")
    else:
        output.write_text(rendered)


if __name__ == "__main__":
    main()
